#!/usr/bin/env python3
"""
Export the learned track from the robot and turn it into a speed plan.

  python3 tools/export_track.py /dev/ttyUSB0          # read from the robot
  python3 tools/export_track.py --csv tracks/x.csv    # reuse a saved export

Writes:
  tracks/track_<date>.csv   the raw map (distance, heading, events)
  AllInOne/track_map.h      speed plan + landmarks, used by the race firmware

Then compile and flash AllInOne with USE_TRACK_MAP 1.

Speed plan: each point gets the fastest speed that keeps sideways
acceleration under --alat on the curve ahead, slows down before corners,
junctions and gaps, and respects braking (--adec) and acceleration (--aacc)
limits. Speeds are in mm/s; the firmware converts them to motor commands.
"""
import argparse, datetime, fcntl, math, os, struct, sys, termios, time

FLAG_J, FLAG_CL, FLAG_CR, FLAG_GAP, FLAG_LOST = 1, 2, 4, 8, 16
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def read_from_robot(port, timeout=15.0):
    """Send 'export' and capture until TRACK_END. Keeps DTR/RTS released so
    the ESP32 is not reset when the port opens."""
    fd = os.open(port, os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
    attrs = termios.tcgetattr(fd)
    attrs[0] = 0; attrs[1] = 0; attrs[3] = 0
    attrs[2] = termios.CS8 | termios.CREAD | termios.CLOCAL
    attrs[4] = attrs[5] = termios.B115200
    termios.tcsetattr(fd, termios.TCSANOW, attrs)
    TIOCMBIC, DTR, RTS = 0x5417, 2, 4
    fcntl.ioctl(fd, TIOCMBIC, struct.pack('I', DTR | RTS))
    time.sleep(0.3)
    try:
        os.read(fd, 65536)
    except BlockingIOError:
        pass
    os.write(fd, b'export\n')
    buf, end = b'', time.time() + timeout
    while time.time() < end:
        try:
            buf += os.read(fd, 4096)
        except BlockingIOError:
            time.sleep(0.05)
        if b'TRACK_END' in buf and b'\n' in buf[buf.find(b'TRACK_END'):]:
            break
    os.close(fd)
    text = buf.decode(errors='replace')
    if 'TRACK_EXPORT none' in text:
        sys.exit("The robot has no saved map. Do a learning run first.")
    if 'TRACK_EXPORT v1' not in text or 'TRACK_END' not in text:
        sys.exit("No complete export received. Is the robot connected and running? Got:\n" + text[-500:])
    return text[text.index('TRACK_EXPORT v1'):text.index('TRACK_END')]


def parse_export(text):
    rows = []
    for line in text.splitlines():
        parts = line.strip().split(',')
        if len(parts) == 3 and parts[0].isdigit():
            rows.append((float(parts[0]), float(parts[1]), int(parts[2])))
    if len(rows) < 5:
        sys.exit("Map has only %d samples; the learning run was too short." % len(rows))
    return rows


def unwrap(deg):
    out, prev, off = [], deg[0], 0.0
    for d in deg:
        if d - prev > 180: off -= 360
        elif d - prev < -180: off += 360
        out.append(d + off)
        prev = d
    return out


def plan(rows, a):
    s = [r[0] for r in rows]
    head = [math.radians(h) for h in unwrap([r[1] for r in rows])]
    flags = [r[2] for r in rows]
    n = len(s)
    # curvature from heading change over a +/-w sample window (smooths noise)
    w = max(1, int(a.window_mm / max(1.0, s[1] - s[0])))
    curv = []
    for i in range(n):
        i0, i1 = max(0, i - w), min(n - 1, i + w)
        ds = s[i1] - s[i0]
        curv.append(abs(head[i1] - head[i0]) / ds if ds > 0 else 0.0)
    v = []
    for i in range(n):
        lim = a.vmax
        if curv[i] > 1e-6:
            lim = min(lim, math.sqrt(a.alat / curv[i]))
        if flags[i] & (FLAG_CL | FLAG_CR): lim = min(lim, a.corner_speed)
        if flags[i] & FLAG_J:              lim = min(lim, a.junction_speed)
        if flags[i] & (FLAG_GAP | FLAG_LOST): lim = min(lim, a.gap_speed)
        v.append(max(a.vmin, lim))
    # braking: must be able to slow down for what comes next
    for i in range(n - 2, -1, -1):
        v[i] = min(v[i], math.sqrt(v[i + 1] ** 2 + 2 * a.adec * (s[i + 1] - s[i])))
    # acceleration limit
    for i in range(1, n):
        v[i] = min(v[i], math.sqrt(v[i - 1] ** 2 + 2 * a.aacc * (s[i] - s[i - 1])))
    v[0] = min(v[0], a.vstart)
    # landmarks: first sample of each run of a junction/corner flag
    lms, prev = [], 0
    for i in range(n):
        f = flags[i] & (FLAG_J | FLAG_CL | FLAG_CR)
        for bit in (FLAG_J, FLAG_CL, FLAG_CR):
            if f & bit and not prev & bit:
                lms.append((int(s[i]), bit))
        prev = f
    return s, v, curv, lms


def write_header(path, s, v, lms, a):
    with open(path, 'w') as f:
        f.write("// Generated by tools/export_track.py on %s. Do not edit by hand.\n" %
                datetime.datetime.now().strftime('%Y-%m-%d %H:%M'))
        f.write("// Profile limits: alat=%g adec=%g aacc=%g mm/s^2, vmax=%g mm/s\n" %
                (a.alat, a.adec, a.aacc, a.vmax))
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define TRACK_MAP_POINTS %d\n" % len(s))
        f.write("#define TRACK_MAP_LENGTH_MM %d\n" % int(s[-1]))
        f.write("const uint16_t TRACK_MAP_S[TRACK_MAP_POINTS] = {%s};\n" % ",".join(str(int(x)) for x in s))
        f.write("const uint16_t TRACK_MAP_V[TRACK_MAP_POINTS] = {%s};\n\n" % ",".join(str(int(round(x))) for x in v))
        f.write("#define TRACK_MAP_LANDMARKS %d\n" % len(lms))
        if lms:
            f.write("const uint16_t TRACK_MAP_LM_S[TRACK_MAP_LANDMARKS] = {%s};\n" % ",".join(str(x[0]) for x in lms))
            f.write("const uint8_t  TRACK_MAP_LM_TYPE[TRACK_MAP_LANDMARKS] = {%s};\n" % ",".join(str(x[1]) for x in lms))
        else:
            f.write("const uint16_t TRACK_MAP_LM_S[1] = {0};\nconst uint8_t TRACK_MAP_LM_TYPE[1] = {0};\n")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('port', nargs='?', help='serial port, e.g. /dev/ttyUSB0')
    p.add_argument('--csv', help='use a saved export instead of the robot')
    p.add_argument('--out', default=os.path.join(ROOT, 'AllInOne', 'track_map.h'))
    p.add_argument('--alat', type=float, default=1500, help='max sideways accel in curves, mm/s^2')
    p.add_argument('--adec', type=float, default=1500, help='max braking, mm/s^2')
    p.add_argument('--aacc', type=float, default=1000, help='max acceleration, mm/s^2')
    p.add_argument('--vmax', type=float, default=1000, help='top speed on straights, mm/s')
    p.add_argument('--vmin', type=float, default=100, help='never plan slower than this, mm/s')
    p.add_argument('--vstart', type=float, default=150, help='speed at the start, mm/s')
    p.add_argument('--corner-speed', type=float, default=120)
    p.add_argument('--junction-speed', type=float, default=200)
    p.add_argument('--gap-speed', type=float, default=200)
    p.add_argument('--window-mm', type=float, default=60, help='curvature smoothing window')
    a = p.parse_args()

    if a.csv:
        text = open(a.csv).read()
    elif a.port:
        text = read_from_robot(a.port)
        os.makedirs(os.path.join(ROOT, 'tracks'), exist_ok=True)
        path = os.path.join(ROOT, 'tracks', 'track_%s.csv' % datetime.datetime.now().strftime('%Y%m%d_%H%M%S'))
        open(path, 'w').write(text)
        print("Saved raw export:", path)
    else:
        sys.exit("Give a serial port or --csv FILE")

    rows = parse_export(text)
    s, v, curv, lms = plan(rows, a)
    write_header(a.out, s, v, lms, a)

    names = {FLAG_J: 'junction', FLAG_CL: 'corner left', FLAG_CR: 'corner right'}
    print("Track length: %.0f mm, %d points, %d landmarks" % (s[-1], len(s), len(lms)))
    for d, t in lms:
        print("  %6d mm  %s" % (d, names[t]))
    print("Planned speed: min %.0f, max %.0f, mean %.0f mm/s" % (min(v), max(v), sum(v) / len(v)))
    print("Wrote", a.out, "- now compile and flash AllInOne (USE_TRACK_MAP 1).")


if __name__ == '__main__':
    main()
